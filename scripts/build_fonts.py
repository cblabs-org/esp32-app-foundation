import argparse
import os
import sys


def parse_args():
    """
    @brief Parse command-line arguments.
    @return argparse.Namespace with input_dir and output fields.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Generate a C++ header containing custom U8G2 font byte arrays "
            "from BDF font source files.\n\n"
            "NOTE: The ESP32 App Foundation ships only U8G2 built-in font\n"
            "aliases (see modules/u8g2Display/fonts/fonts.hpp). Use this\n"
            "script when your application needs custom BDF-compiled fonts."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--input-dir",
        required=True,
        help="Directory containing .bdf font source files.",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Output path for the generated .hpp header file.",
    )
    return parser.parse_args()


def discover_bdf_files(input_dir):
    """
    @brief Discover all .bdf files in the given directory (non-recursive).
    @param input_dir  Path to the directory to scan.
    @return Sorted list of absolute paths to .bdf files found.
    """
    if not os.path.isdir(input_dir):
        print(f"[build_fonts] Warning: Input directory '{input_dir}' does not exist.")
        return []

    bdf_files = sorted(
        os.path.join(input_dir, f)
        for f in os.listdir(input_dir)
        if f.lower().endswith(".bdf") and os.path.isfile(os.path.join(input_dir, f))
    )
    return bdf_files


def _sanitize_name(filename):
    """
    @brief Convert a BDF filename into a valid C identifier.
    @param filename  The basename of the .bdf file (e.g. "my-font_10pt.bdf").
    @return A C-safe identifier string (e.g. "my_font_10pt").
    """
    name = os.path.splitext(filename)[0]
    # Replace any non-alphanumeric character with underscore
    return "".join(c if c.isalnum() else "_" for c in name)


def generate_header(bdf_files, output_path):
    """
    @brief Generate the C++ header content from a list of BDF file paths.

    For each BDF file, an extern declaration is emitted for a const uint8_t[]
    array whose symbol name is derived from the filename. The actual byte array
    definitions must be generated by the U8G2 bdfconv tool and compiled
    separately — this header provides only the extern declarations for linking.

    @param bdf_files    List of absolute paths to .bdf files.
    @param output_path  The repository-relative output path (for the module header).
    @return The complete header file content as a string.
    """
    guard = os.path.basename(output_path).replace(".", "_").upper() + "_"

    lines = []

    # --- House-style module header ---
    lines.append("/*")
    lines.append(" * ESP32 App Foundation (c) 2026 CB Labs")
    lines.append(" *")
    lines.append(" * https://github.com/matthewmcneill/esp32-app-foundation")
    lines.append(" *")
    lines.append(" * This work is licensed under Creative Commons Attribution-NonCommercial-ShareAlike 4.0 International.")
    lines.append(" * To view a copy of this license, visit https://creativecommons.org/licenses/by-nc-sa/4.0/")
    lines.append(" *")
    lines.append(f" * Module: {output_path}")
    lines.append(" * Description: Auto-generated header declaring extern font byte arrays for")
    lines.append(" *              custom BDF-compiled U8G2 fonts. The actual byte array")
    lines.append(" *              definitions must be produced by the U8G2 bdfconv tool.")
    lines.append(" *")

    if bdf_files:
        lines.append(" * Exported Declarations:")
        for bdf in bdf_files:
            sym = _sanitize_name(os.path.basename(bdf))
            lines.append(f" * - {sym}: extern const uint8_t[] font data for {os.path.basename(bdf)}")
    else:
        lines.append(" * Exported Declarations: (none — no BDF files were found)")

    lines.append(" */")
    lines.append("")
    lines.append(f"#ifndef {guard}")
    lines.append(f"#define {guard}")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")

    if not bdf_files:
        lines.append("// No custom BDF font files were found in the input directory.")
        lines.append("// To add custom fonts:")
        lines.append("//   1. Place .bdf source files in your input directory.")
        lines.append("//   2. Re-run this script to regenerate declarations.")
        lines.append("//   3. Use the U8G2 bdfconv tool to produce the byte array definitions.")
    else:
        for bdf in bdf_files:
            sym = _sanitize_name(os.path.basename(bdf))
            lines.append(f"/** @brief Custom font data compiled from {os.path.basename(bdf)}. */")
            lines.append(f"extern const uint8_t {sym}[];")
            lines.append("")

    lines.append("")
    lines.append(f"#endif // {guard}")
    lines.append("")

    return "\n".join(lines)


def main():
    """
    @brief Entry point — discover BDF files and write the generated header.
    """
    args = parse_args()

    bdf_files = discover_bdf_files(args.input_dir)

    if bdf_files:
        print(f"[build_fonts] Found {len(bdf_files)} BDF file(s) in '{args.input_dir}':")
        for f in bdf_files:
            print(f"  - {os.path.basename(f)}")
    else:
        print(f"[build_fonts] No .bdf files found in '{args.input_dir}'. "
              "Generating stub header.")

    header_content = generate_header(bdf_files, args.output)

    # Ensure output directory exists
    out_dir = os.path.dirname(args.output)
    if out_dir and not os.path.exists(out_dir):
        os.makedirs(out_dir)

    with open(args.output, "w") as f:
        f.write(header_content)

    print(f"[build_fonts] Header written to '{args.output}'")


if __name__ == "__main__":
    main()
